import test from 'node:test';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {mkdtemp, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import sharp from 'sharp';
import {Config as PiAiConfig} from '@deepseek-ai/dsh-llm-pi-ai';
import {LocalAttachmentStore, prepareImageFile, readRequestImageFile} from '@deepseek-ai/dsh-attachment-local';
import {requestImageDimensions} from '@deepseek-ai/dsh-attachment';
import {IMAGE_MAX_BYTES} from '@mote/shared';
import {createRuntimePatch} from '../dist/runtime/dsh/profile-compiler.js';
import {startBridge} from '../dist/bridge.js';

const sha256 = data => createHash('sha256').update(data).digest('hex');
const rgb = Buffer.alloc(1024 * 1024 * 3);
let seed = 57;
for (let i = 0; i < rgb.length; i++) {
  seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
  rgb[i] = seed >>> 24;
}
const original = await sharp(rgb, {raw: {width: 1024, height: 1024, channels: 3}}).png({compressionLevel: 0}).toBuffer();
assert.equal(original.length, 3_151_914);

function sdkConfiguration(protocol, directory) {
  const patch = JSON.parse(createRuntimePatch('/generated/context.mjs', 'generated-original-model', 'http://127.0.0.1:9/v1', 'off', 8192, {protocol, contextWindow: 98_304}));
  const entries = patch.flatMap(entry => entry.insert ?? []);
  const store = LocalAttachmentStore.Config({dshHome: directory, ...entries.find(entry => entry.id === 'mote-attachments').config});
  const providers = PiAiConfig(entries.find(entry => entry.id === 'mote-llm').config).providers.get();
  return {store, provider: Object.values(providers)[0], normalization: {maxPixels: store.normalizedImageMaxPixels, maxDimension: store.normalizedImageMaxDimension, maxBytes: store.normalizedImageMaxBytes}};
}

test('actual SDK request-image conversion preserves the full original bytes and RGB under the emitted provider profile', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'mote-original-request-'));
  t.after(() => rm(directory, {recursive: true, force: true}));
  for (const protocol of ['openai-completions', 'openai-responses', 'anthropic-messages', 'google-generative-ai']) await t.test(protocol, async () => {
    const config = sdkConfiguration(protocol, directory);
    const saved = await prepareImageFile({data: original, mediaType: 'image/png', name: 'capture'}, config.store, config.normalization);
    const dimensions = requestImageDimensions(saved.ref.width, saved.ref.height, config.provider.requestImagePixelBudget);
    const actual = await readRequestImageFile(join(directory, protocol), saved, {...dimensions, maxBytes: config.provider.requestImageMaxBytes});
    assert.equal(actual.mediaType, 'image/png');
    assert.equal(actual.data.length, original.length);
    assert.equal(sha256(actual.data), sha256(original), 'the actual SDK must not silently replace the Host-pinned original');
    const pixels = await sharp(actual.data).removeAlpha().toColourspace('srgb').raw().toBuffer();
    assert.equal(pixels.length, rgb.length);
    assert.equal(sha256(pixels), sha256(rgb));
    t.diagnostic(JSON.stringify({protocol,encodedBytes:actual.data.length,encodedSha256:sha256(actual.data),rgbBytes:pixels.length,rgbSha256:sha256(pixels),requestImageMaxBytes:config.provider.requestImageMaxBytes}));
  });
});

test('the Host and actual SDK still reject an original above the existing 8 MiB admission cap', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'mote-over-cap-request-'));
  t.after(() => rm(directory, {recursive: true, force: true}));
  const config = sdkConfiguration('openai-completions', directory);
  const oversized = await sharp({create: {width: 2048, height: 1366, channels: 3, background: '#578abd'}}).png({compressionLevel: 0}).toBuffer();
  assert.equal(config.store.maxImageBytes, IMAGE_MAX_BYTES);
  assert.ok(oversized.length > IMAGE_MAX_BYTES);
  assert.ok(oversized.toString('base64').length < 12 * 1024 * 1024, 'exercise the Host decoded-byte cap independently of its encoded-string cap');
  await assert.rejects(prepareImageFile({data: oversized, mediaType: 'image/png', name: 'capture'}, config.store, config.normalization), error => error.code === 'IMAGE_TOO_LARGE');

  const id = 'b54d3aaa-4ca3-5073-bb47-ad2db6e84a13';
  const record = {id, capturedAt: '2026-11-17T00:00:00Z', appName: 'Generated oversize image', deviceId: 'generated', sourceType: 'screen', ocrText: 'Generated byte-cap evidence'};
  let reads = 0;
  const bridge = await startBridge({search: async () => [record], timeline: async () => ({items: [record], nextCursor: null}), evidence: async () => [record], activity: async () => ({}), devices: async () => [], readImage: async () => {reads++; return {mimeType: 'image/png', data: oversized.toString('base64')};}}, {question: 'Inspect the generated byte-cap image'}, 8);
  t.after(() => bridge.close());
  const invoke = async (tool, args) => {
    const response = await fetch(bridge.url + '/' + tool, {method: 'POST', headers: {Authorization: 'Bearer ' + bridge.token, 'Content-Type': 'application/json'}, body: JSON.stringify(args)});
    return {status: response.status, body: await response.json()};
  };
  assert.equal((await invoke('search_context', {query: 'Generated byte-cap evidence'})).status, 200);
  assert.equal((await invoke('evidence', {ids: [id]})).status, 200);
  const denied = await invoke('read_image', {id});
  assert.equal(denied.status, 400);
  assert.equal(denied.body.toolError.code, 'invalid_image_region');
  assert.equal(denied.body.toolError.message, 'Invalid image output size');
  assert.equal(reads, 1);
  assert.equal(denied.body.image, undefined);
  assert.equal(denied.body.imageDelivery, undefined);
  assert.deepEqual(bridge.imageReadReceipts, [], 'over-cap bytes never acquire an image receipt');
  t.diagnostic(JSON.stringify({hostImageMaxBytes:IMAGE_MAX_BYTES,oversizedBytes:oversized.length,hostStatus:denied.status,sdkCode:'IMAGE_TOO_LARGE',imageReceipts:bridge.imageReadReceipts.length}));
});
