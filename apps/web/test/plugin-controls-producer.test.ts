import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {randomUUID} from 'node:crypto';
import React,{act} from 'react';
import {JSDOM} from 'jsdom';
import type {PluginBuildView,MemoryBindingView} from '@mote/shared';
import {configureLocale} from '@mote/shared/i18n';
import {buildApp} from '../../server/src/app.js';
import type {Config} from '../../server/src/config.js';
import type {Api} from '../src/api.js';
import {ApiError} from '../src/api.js';

configureLocale(()=> 'zh-CN');
const dom=new JSDOM('<html><body></body></html>',{url:'http://localhost/#/system/plugins'});
Object.assign(globalThis,{window:dom.window,document:dom.window.document,HTMLElement:dom.window.HTMLElement,IS_REACT_ACT_ENVIRONMENT:true});
dom.window.confirm=()=>true;
const {createRoot}=await import('react-dom/client');
const {PluginCenter}=await import('../src/plugins/plugin-center/PluginCenter.js');
const {ServerSettings}=await import('../src/ServerSettings.js');
const {sourcePluginForSetup}=await import('../src/plugins/sources/registry.js');

test('the real Central response drives plugin switches, stopped-source guidance and the separate automatic-memory settings',async t=>{
  const directory=mkdtempSync(join(tmpdir(),'mote-plugin-web-contract-')),owner='generated-web-owner-'+randomUUID();
  const config:Config={dataDir:directory,token:owner,tokenPath:join(directory,'owner-token'),host:'127.0.0.1',port:0,profile:'test',tokenFromEnvironment:true,maxStorageBytes:30*1024*1024,maxExportBytes:1024*1024,retentionDays:0,insightIntervalHours:0,allowedOrigins:[],model:'',modelBaseUrl:'https://api.deepseek.com',apiKey:'',allowUnauthenticatedLocal:false,embeddingModel:'',embeddingBaseUrl:'',embeddingApiKey:'',logLevel:'silent',connectors:{directory:join(directory,'connectors'),mcpEnabled:false}};
  const node=await buildApp(config,{backgroundWorker:false,agent:{configured:false,async query(){throw Error('No models in the UI/HTTP contract');},async close(){}}});
  const writes:{path:string;body:unknown}[]=[];
  const api={request:async(path:string,init?:RequestInit)=>{
    if(init?.signal?.aborted)throw new DOMException('Aborted','AbortError');
    const method=init?.method??'GET',body=init?.body?JSON.parse(String(init.body)):undefined;
    if(method!=='GET')writes.push({path,body});
    const response=await node.app.inject({url:path,method:method as 'GET'|'POST'|'PATCH',headers:{authorization:'Bearer '+owner},...(body?{payload:body}:{})});
    if(response.statusCode>=400)throw new ApiError(response.json().message??response.json().error,response.statusCode);
    return response.json();
  }} as unknown as Api;
  const element=document.createElement('div');document.body.appendChild(element);const root=createRoot(element);
  t.after(async()=>{await act(async()=>root.unmount());element.remove();await node.app.close();rmSync(directory,{recursive:true,force:true});});
  const settle=async()=>{await new Promise(resolve=>setTimeout(resolve,20));};
  const click=async(name:string)=>{const button=[...element.querySelectorAll<HTMLButtonElement>('button')].find(value=>value.textContent===name||value.getAttribute('aria-label')===name);assert.ok(button,'control '+name);await act(async()=>{button.click();await settle();});};
  await act(async()=>{root.render(React.createElement(PluginCenter,{api,onPage:()=>{}}));await settle();});
  assert.equal(element.querySelector('h1')?.textContent,'插件中心');
  assert.equal(element.querySelector('.plugin-memory-control'),null);
  assert.equal(element.querySelectorAll('.plugin-official-catalog article').length,4);
  assert.doesNotMatch(element.querySelector('.plugin-official-catalog')!.textContent!,/夹具|Mem0|Hindsight|Developer API/);
  await click('已安装插件');
  const gmail=element.querySelector<HTMLButtonElement>('[role=switch][aria-label=Gmail]');assert.ok(gmail);assert.equal(gmail.getAttribute('aria-checked'),'true');
  assert.equal(element.querySelector('[role=switch][aria-label=MCP]'),null,'host dependencies are not optional package controls');
  await act(async()=>{gmail.click();await settle();});
  const builds=(await api.request<PluginBuildView[]>('/api/plugin-builds'));
  assert.equal(builds.find(value=>value.id==='bundled:gmail')!.observed,'stopped');
  assert.equal(element.querySelector('[role=switch][aria-label=Gmail]')!.getAttribute('aria-checked'),'false');
  assert.deepEqual(writes.map(value=>value.path),['/api/plugin-builds/bundled%3Agmail']);
  await act(async()=>{root.render(React.createElement(React.Fragment,null,sourcePluginForSetup('gmail')!.setup!.render({api,catalog:null,refresh:async()=>{},requested:true})));await settle();});
  assert.match(element.textContent!,/插件已停用/);assert.equal(element.querySelector('a')?.getAttribute('href'),'#/system/plugins?tab=installed');
  assert.doesNotMatch(element.textContent!,/尚未授权|重新授权/,'stopping a plugin never pretends its saved account authorization was revoked');
  dom.window.history.replaceState(null,'','#/system/models?category=memory');
  await act(async()=>{root.render(React.createElement(ServerSettings,{api,onNavigate:()=>{},onModelApplied:()=>{}}));await settle();});
  assert.ok(element.querySelector('#model-tab-memory .plugin-memory-control'));
  assert.equal(element.querySelector('.plugin-official-catalog'),null);
  assert.equal([...element.querySelectorAll('[role=tab]')].find(value=>value.textContent==='自动记忆')?.getAttribute('aria-selected'),'true');
  const automatic=element.querySelector<HTMLButtonElement>('.plugin-memory-control [role=switch]');assert.ok(automatic);assert.equal(automatic.getAttribute('aria-checked'),'true');
  await act(async()=>{automatic.click();await settle();});
  const binding=await api.request<MemoryBindingView>('/api/memory-spaces/default/binding');
  assert.equal(binding.admission.desired,false);assert.equal(writes.at(-1)?.path,'/api/memory-spaces/default/binding/pause');
});
