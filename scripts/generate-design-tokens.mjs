import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const root=new URL('../',import.meta.url);
const tokens=JSON.parse(readFileSync(new URL('packages/shared/design-tokens.json',root),'utf8'));
const lightTokens=JSON.parse(readFileSync(new URL('packages/shared/design-tokens.light.json',root),'utf8'));
if(JSON.stringify(Object.keys(tokens))!==JSON.stringify(Object.keys(lightTokens)))throw Error('Light/dark theme roles differ');
const layout={id:'mote.android',version:'1',primary:['home'],initial:'home',navigation:'home',detail:'stack'};
const name=key=>key.replace(/-([a-z])/g,(_,c)=>c.toUpperCase());
const isColor=value=>/^#[\da-f]{6}(?:[\da-f]{2})?$/i.test(value);
// CSS and Swift literals keep the source #rrggbbaa order; Android assets and
// resources use #aarrggbb so android.graphics.Color.parseColor reads them correctly.
const androidColor=value=>isColor(value)&&value.length===9?`#${value.slice(7,9)}${value.slice(1,7)}`:value;
const androidTokens=values=>Object.fromEntries(Object.entries(values).map(([key,value])=>[key,androidColor(value)]));
const colors=Object.entries(tokens).filter(([,value])=>isColor(value));
const dimensions=Object.entries(tokens).filter(([,value])=>/^\d+px$/.test(value));
const mobileRadii=dimensions.filter(([key])=>key.startsWith('radius-')&&key.endsWith('-mobile'));
const numbers=Object.entries(tokens).filter(([,value])=>/^\d+(?:\.\d+)?$/.test(value));
const declarations=values=>Object.entries(values).map(([key,value])=>`  --mote-${key}: ${value};`).join('\n');
const androidDimensions=values=>values.map(([key,value])=>`    <dimen name="mote_${key.replaceAll('-', '_')}">${Number.parseInt(value,10)}dp</dimen>`).join('\n');
const css='/* Generated by scripts/generate-design-tokens.mjs. */\n:root {\n  color-scheme: light;\n'+declarations(lightTokens)+'\n}\n@media (prefers-color-scheme: dark) {\n  :root:not([data-color-scheme="light"]) { color-scheme: dark;\n'+declarations(tokens)+'\n  }\n}\n:root[data-color-scheme="dark"] { color-scheme: dark;\n'+declarations(tokens)+'\n}\n';
const outputs=new Map(['web','desktop'].map(app=>[`apps/${app}/src/design-tokens.css`,css]));
outputs.set('packages/shared/src/ui-theme.generated.ts','// Generated by scripts/generate-design-tokens.mjs.\nexport const linearThemeTokens = '+JSON.stringify(tokens,null,2)+' as const;\nexport const linearLightThemeTokens = '+JSON.stringify(lightTokens,null,2)+' as const;\n');
outputs.set('apps/android/app/src/main/java/dev/mote/collector/DesignTokens.kt','// Generated by scripts/generate-design-tokens.mjs.\npackage dev.mote.collector\n\nobject DesignTokens {\n'+colors.map(([key,value])=>`    val ${name(key)} = android.graphics.Color.parseColor("${androidColor(value)}")`).join('\n')+'\n'+dimensions.map(([key,value])=>`    const val ${name(key)} = ${Number.parseInt(value,10)}`).join('\n')+'\n'+numbers.map(([key,value])=>`    const val ${name(key)} = ${value}`).join('\n')+'\n}\n');
outputs.set('apps/android/app/src/main/res/values-night/design-tokens.xml','<!-- Generated by scripts/generate-design-tokens.mjs. -->\n<resources>\n'+colors.map(([key,value])=>`    <color name="mote_${key.replaceAll('-', '_')}">${androidColor(value)}</color>`).join('\n')+'\n'+androidDimensions(mobileRadii)+'\n</resources>\n');
outputs.set('apps/android/app/src/main/res/values/design-tokens.xml','<!-- Generated by scripts/generate-design-tokens.mjs. -->\n<resources>\n'+colors.map(([key])=>`    <color name="mote_${key.replaceAll('-', '_')}">${androidColor(lightTokens[key])}</color>`).join('\n')+'\n'+androidDimensions(mobileRadii)+'\n</resources>\n');
outputs.set('apps/android/app/src/main/assets/design-tokens.json',JSON.stringify(androidTokens(tokens),null,2)+'\n');
const swiftColors=colors.map(([key])=>`    public static let ${name(key)} = MoteColorToken(light: "${lightTokens[key]}", dark: "${tokens[key]}")`).join('\n');
const swiftDimensions=dimensions.map(([key,value])=>`        public static let ${name(key)}: CGFloat = ${Number.parseInt(value,10)}`).join('\n');
const swiftNumbers=numbers.map(([key,value])=>`        public static let ${name(key)}: CGFloat = ${value}`).join('\n');
outputs.set('apps/ios/MoteKit/Sources/MoteDesign/DesignTokens.swift',`// Generated by scripts/generate-design-tokens.mjs. Do not edit.
import CoreGraphics

/// A design color with the light and dark values from the shared token source.
public struct MoteColorToken: Sendable, Equatable {
    public let light: String
    public let dark: String

    public init(light: String, dark: String) {
        self.light = light
        self.dark = dark
    }
}

public enum MoteDesignTokens {
${swiftColors}

    public enum Dimens {
${swiftDimensions}
    }

    public enum Numbers {
${swiftNumbers}
    }
}
`);
const theme={id:'mote.linear',version:'1',tokens:androidTokens(tokens),schemes:{light:androidTokens(lightTokens),dark:androidTokens(tokens)}};
outputs.set('apps/android/app/src/main/assets/ui-presentation.json',JSON.stringify({schemaVersion:1,theme,layout},null,2)+'\n');
const bootstrap=`// Generated by scripts/generate-design-tokens.mjs; runs before styles and application paint.
(()=>{let preference='auto',scheme;const initial=window.mote?.initialAppearance;
if(initial){preference=initial.preference;scheme=initial.scheme;}else{try{preference=localStorage.getItem('mote.appearance.v1');}catch{}let dark=false;try{dark=matchMedia('(prefers-color-scheme: dark)').matches;}catch{}scheme=preference==='dark'||(preference!=='light'&&dark)?'dark':'light';}
const colors=${JSON.stringify({light:lightTokens.background,dark:tokens.background})};
document.documentElement.dataset.colorScheme=scheme;document.documentElement.style.colorScheme=scheme;document.documentElement.style.backgroundColor=colors[scheme];
const meta=document.querySelector('meta[name="theme-color"]');if(meta)meta.content=colors[scheme];
})();
`;
outputs.set('apps/web/public/appearance-init.js',bootstrap);
outputs.set('apps/desktop/src/appearance-init.js',bootstrap);
const check=process.argv.includes('--check');
for(const [path,value] of outputs){
  const url=new URL(path,root);
  if(check){if(readFileSync(url,'utf8')!==value)throw Error('Stale generated UI resource: '+path);}
  else writeFileSync(fileURLToPath(url),value);
}
