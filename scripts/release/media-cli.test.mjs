import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,mkdir,readFile,writeFile,rm} from 'node:fs/promises';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {mediaAssetStatusSchema} from '@mote/shared';
import {initialize,profilePaths,loadProfile,atomicJson,repository} from '../profile-lib.mjs';

const cli=fileURLToPath(new URL('../mote.mjs',import.meta.url));
async function fixture(t){
 const home=await mkdtemp(join(tmpdir(),'mote-media-cli-')),paths=profilePaths('core03',home);
 t.after(()=>rm(home,{recursive:true,force:true}));await initialize(paths,{port:49173});
 const run=(args,env={})=>spawnSync(process.execPath,[cli,...args,'--profile',paths.profile,'--home',home],{cwd:repository,env:{...process.env,...env},encoding:'utf8',timeout:30_000});
 return {home,paths,run};
}

test('the real CLI requires a runtime role and passes only that role to preparation without claiming a running worker',async t=>{
 const {home,paths,run}=await fixture(t),profile=await loadProfile(paths),release=join(home,'generated-release');
 await mkdir(join(release,'apps/server/dist'),{recursive:true});
 // Only the unavailable dependency installer is replaced. CLI parsing, private
 // profile loading, locking, role selection and JSON output remain real.
 await writeFile(join(release,'apps/server/dist/media-native-runtime.mjs'),`
 import {mkdir,writeFile} from 'node:fs/promises';import {join} from 'node:path';
 export async function prepareNativeMediaRuntime(options){
  await mkdir(options.directory,{recursive:true});
  await writeFile(join(options.directory,'generated-call.json'),JSON.stringify({role:options.role,repository:options.repository,sourcePython:options.sourcePython,signal:options.signal instanceof AbortSignal}));
  return {created:true,python:'generated-python',version:'generated-environment',generation:'generated'};
 }
 `);
 await atomicJson(paths.metaFile,{...profile.meta,release});
 const missing=run(['media-runtime']);assert.equal(missing.status,1);assert.match(missing.stderr,/requires --role/);
 const invalid=run(['media-runtime','--role','speaker-wespeaker']);assert.equal(invalid.status,1);assert.match(invalid.stderr,/requires --role/);
 for(const role of ['ocr','dialogue','local-image']){
  const result=run(['media-runtime','--role',role,'--python','generated-python']);assert.equal(result.status,0,result.stderr);
  assert.deepEqual(JSON.parse(result.stdout),{profile:paths.profile,role,installed:true,changed:true,python:'generated-python',runtimeReady:false});
  assert.deepEqual(JSON.parse(await readFile(join(profile.modelDirectory,'runtime/generated-call.json'),'utf8')),{role,repository:release,sourcePython:'generated-python',signal:true});
 }
 const reloaded=await loadProfile(paths);assert.deepEqual(reloaded.document,profile.document,'preparing a role does not replace user configuration');
 assert.ok(profile.document.media.localImagePort>=10000&&profile.document.media.localImagePort<20000);assert.notEqual(profile.document.media.localImagePort,profile.document.media.asrPort);assert.notEqual(profile.document.media.localImagePort,profile.document.media.ocrPort);
 assert.equal(profile.document.media.localImageEndpoint,`http://127.0.0.1:${profile.document.media.localImagePort}/v1/interpret`);
 assert.equal(profile.env.MOTE_MEDIA_PYTHON,'python3','an executable name must not become a nonexistent profile-relative path');
});

test('top-level local-image import feeds its real verified receipt to the shared consumer and rejects corrupt generated bytes',async t=>{
 const {home,paths,run}=await fixture(t),profile=await loadProfile(paths),bundle=join(home,'bundle'),bytes=Buffer.from('Generated local-image offline asset');
 await mkdir(join(bundle,'component'),{recursive:true});await writeFile(join(bundle,'component/model.bin'),bytes);
 const preload=join(home,'generated-catalog.mjs'),assetsUrl=pathToFileURL(join(repository,'apps/server/dist/media-assets.js')).href;
 // Generate the catalog at the model boundary; retain the production importer,
 // hash/size checks, staging publication, profile lock and receipt serializer.
 await writeFile(preload,`import {MEDIA_CATALOG} from ${JSON.stringify(assetsUrl)};MEDIA_CATALOG['local-image']=${JSON.stringify({version:'generated-core03-image',files:[{name:'component/model.bin',size:bytes.length,sha256:createHash('sha256').update(bytes).digest('hex'),official:'https://example.invalid/generated-model'}]})};`);
 const env={NODE_OPTIONS:`--import=${pathToFileURL(preload).href}`};
 const result=run(['media-import','--role','local-image','--from',bundle],env);assert.equal(result.status,0,result.stderr);
 const receipt=mediaAssetStatusSchema.parse(JSON.parse(result.stdout));assert.equal(receipt.role,'local-image');assert.equal(receipt.state,'ready');assert.equal(receipt.bytes,bytes.length);
 const installed=JSON.parse(await readFile(join(profile.modelDirectory,'local-image/complete.json'),'utf8'));assert.equal(installed.version,receipt.version);
 await writeFile(join(bundle,'component/model.bin'),Buffer.alloc(bytes.length));
 const corrupt=run(['media-import','--role','local-image','--from',bundle],env);assert.equal(corrupt.status,1);assert.match(corrupt.stderr,/Invalid model asset: component\/model.bin/);
 assert.deepEqual(await readFile(join(profile.modelDirectory,'local-image/component/model.bin')),bytes,'failed re-import preserves the verified installation');
 assert.equal(result.stdout.includes(home),false);assert.equal(corrupt.stderr.includes(bundle),false);
});
