import {readFileSync,writeFileSync} from 'node:fs';
import {createHash,sign} from 'node:crypto';
import {resolve,join} from 'node:path';
import {verifyReleaseEnvelope} from '../../packages/shared/dist/release.js';
import {verifyComponent} from './components.mjs';
import {verifiedReleaseAssets} from './dev-assets.mjs';
const directory=resolve(process.env.MOTE_RELEASE_OUTPUT||'artifacts/release');
const [component,...extra]=process.argv.slice(2);
if(extra.length)throw Error('Usage: node scripts/release/make-manifest.mjs <central|desktop|android>');
const release=verifyComponent(component,{ref:process.env.GITHUB_REF,repository:process.env.GITHUB_REPOSITORY}),version=release.version,policy=JSON.parse(readFileSync('release/signing-policy.json','utf8'));
const names=verifiedReleaseAssets(directory,release,policy),assets=names.map(n=>JSON.parse(readFileSync(join(directory,n+'.asset.json'),'utf8')));
const manifest={schemaVersion:1,component,version,channel:release.channel,repository:policy.repository,tag:release.tag,notesUrl:`https://github.com/${policy.repository}/releases/tag/${release.tag}`,publishedAt:new Date().toISOString(),assets,images:[]};
const payload=Buffer.from(JSON.stringify(manifest));
const key=process.env.MOTE_RELEASE_SIGNING_KEY;
if(!key)throw Error('Release signing secret is required');
const envelope={schemaVersion:1,keyId:policy.keyId,payload:payload.toString('base64'),signature:sign('RSA-SHA256',payload,key).toString('base64')};
const raw=JSON.stringify(envelope,null,2)+'\n';verifyReleaseEnvelope(raw,{repository:policy.repository,channel:manifest.channel,component,version});
writeFileSync(join(directory,'mote-release.json'),raw);
writeFileSync(join(directory,'SHA256SUMS'),assets.map(a=>`${a.sha256}  ${a.name}`).join('\n')+'\n'+createHash('sha256').update(raw).digest('hex')+'  mote-release.json\n');
console.log(JSON.stringify({component,version,assets:assets.length,signed:true}));
